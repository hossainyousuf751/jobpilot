// Builds the web version from the desktop sources, no bundler dependency:
//   web-dist/                              static site for Cloudflare Pages (build command: node scripts/build-web.mjs)
//   supabase/functions/fetch-jobs/index.ts the hourly job fetcher (deployed by the Supabase GitHub integration)
// The pure CommonJS modules (match, insights, …) are wrapped in a tiny require() so browser and Deno run them unchanged.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = (...p) => path.join(root, 'src', ...p);
const out = path.join(root, 'web-dist');

function bundle(names) {
  const mods = names.map((n) => `'./${n}': function (module, exports, require) {\n${fs.readFileSync(src(`${n}.js`), 'utf8')}\n},`).join('\n');
  return `const __mods = {\n${mods}\n};
const __cache = {};
function __req(name) {
  const key = './' + name.replace(/^\\.\\//, '').replace(/\\.js$/, '');
  if (!__mods[key]) throw new Error('module not bundled: ' + name);
  if (!__cache[key]) { const module = { exports: {} }; __cache[key] = module; __mods[key](module, module.exports, __req); }
  return __cache[key].exports;
}\n`;
}

// ---- static site
fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src('ui'), out, { recursive: true });
fs.cpSync(src('web', 'vendor'), path.join(out, 'vendor'), { recursive: true });
for (const f of ['config.js', 'webapi.js']) fs.copyFileSync(src('web', f), path.join(out, f));
fs.writeFileSync(path.join(out, 'core.js'), `// Generated by scripts/build-web.mjs: shared modules from src/.\n${bundle(['insights', 'match', 'cvdoc', 'recruiters'])}window.JP = __req;\n`);

const { url } = new Function('window', `${fs.readFileSync(src('web', 'config.js'), 'utf8')}; return window.JP_CONFIG;`)({});
const host = new URL(url).host;
const csp = `default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; worker-src 'self'; connect-src 'self' https://${host} wss://${host}; frame-ancestors 'none'; base-uri 'self'; form-action 'self'`;
let html = fs.readFileSync(src('ui', 'index.html'), 'utf8');
const replace = (a, b) => { if (!html.includes(a)) throw new Error(`index.html: missing ${a}`); html = html.replace(a, b); };
replace(html.match(/<meta http-equiv="Content-Security-Policy"[^>]*>/)[0], `<meta http-equiv="Content-Security-Policy" content="${csp.replace(/; frame-ancestors 'none'/, '')}">`);
replace('<script src="app.js"></script>', ['vendor/supabase.js', 'vendor/mammoth.browser.min.js', 'core.js', 'config.js', 'webapi.js', 'app.js'].map((s) => `<script src="${s}"></script>`).join('\n  '));
replace(/<webview[^>]*><\/webview>/.exec(html)[0], '<div id="portal"></div>');
fs.writeFileSync(path.join(out, 'index.html'), html);
// Cloudflare Pages response headers (frame-ancestors only works as a header, not in the meta tag).
fs.writeFileSync(path.join(out, '_headers'), `/*\n  Content-Security-Policy: ${csp}\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n  Permissions-Policy: camera=(), microphone=(), geolocation=()\n`);

// ---- Supabase Edge Function
const fn = path.join(root, 'supabase', 'functions', 'fetch-jobs', 'index.ts');
fs.mkdirSync(path.dirname(fn), { recursive: true });
fs.writeFileSync(fn, `// @ts-nocheck\n// Generated by scripts/build-web.mjs from src/sources.js, src/match.js, src/insights.js and src/web/fetcher.js. Do not edit.\n${bundle(['insights', 'match', 'sources'])}${fs.readFileSync(src('web', 'fetcher.js'), 'utf8')}`);

console.log(`web-dist/ (${fs.readdirSync(out).length} files) and supabase/functions/fetch-jobs/index.ts built for ${host}`);
